import { jsPDF } from 'jspdf';

const fontCache: Map<string, ArrayBuffer> = new Map();

async function fetchFont(url: string): Promise<ArrayBuffer> {
  if (fontCache.has(url)) return fontCache.get(url)!;
  const response = await fetch(url);
  if (!response.ok) throw new Error(`Failed to fetch font: ${url}`);
  const buffer = await response.arrayBuffer();
  fontCache.set(url, buffer);
  return buffer;
}

function arrayBufferToBase64(buffer: ArrayBuffer): string {
  const bytes = new Uint8Array(buffer);
  let binary = '';
  for (let i = 0; i < bytes.byteLength; i++) {
    binary += String.fromCharCode(bytes[i]);
  }
  return btoa(binary);
}

async function loadFonts(pdf: jsPDF): Promise<{ heading: string; body: string }> {
  try {
    // Playfair Display for headings — serif, editorial feel
    const [playfairBold, interNormal, interBold] = await Promise.all([
      fetchFont('https://cdn.jsdelivr.net/fontsource/fonts/playfair-display@latest/latin-700-normal.ttf'),
      fetchFont('https://cdn.jsdelivr.net/fontsource/fonts/inter@latest/latin-400-normal.ttf'),
      fetchFont('https://cdn.jsdelivr.net/fontsource/fonts/inter@latest/latin-700-normal.ttf'),
    ]);
    pdf.addFileToVFS('playfair-bold.ttf', arrayBufferToBase64(playfairBold));
    pdf.addFont('playfair-bold.ttf', 'Playfair', 'bold');
    pdf.addFileToVFS('inter-normal.ttf', arrayBufferToBase64(interNormal));
    pdf.addFont('inter-normal.ttf', 'Inter', 'normal');
    pdf.addFileToVFS('inter-bold.ttf', arrayBufferToBase64(interBold));
    pdf.addFont('inter-bold.ttf', 'Inter', 'bold');
    return { heading: 'Playfair', body: 'Inter' };
  } catch {
    return { heading: 'helvetica', body: 'helvetica' };
  }
}

// Color palette
const C = {
  dark: [25, 25, 45] as [number, number, number],
  accent: [79, 70, 229] as [number, number, number],
  accentLight: [238, 235, 255] as [number, number, number],
  text: [45, 45, 65] as [number, number, number],
  textLight: [100, 100, 120] as [number, number, number],
  textMuted: [155, 155, 170] as [number, number, number],
  bg: [252, 252, 255] as [number, number, number],
  cardBg: [244, 244, 250] as [number, number, number],
  border: [215, 215, 228] as [number, number, number],
  white: [255, 255, 255] as [number, number, number],
};

export async function generatePosterPdf(content: Record<string, any>) {
  const orientation = (content.orientation || 'landscape') as 'portrait' | 'landscape';
  const pdf = new jsPDF({ orientation, unit: 'mm', format: 'a4' });
  const fonts = await loadFonts(pdf);

  const pageW = pdf.internal.pageSize.getWidth();
  const pageH = pdf.internal.pageSize.getHeight();
  const margin = 16;
  const contentW = pageW - margin * 2;
  const footerZone = 8; // just "Generated by Mosaic" watermark
  const usableH = pageH - margin - footerZone;

  // Background
  pdf.setFillColor(...C.bg);
  pdf.rect(0, 0, pageW, pageH, 'F');

  // Top accent bar
  pdf.setFillColor(...C.accent);
  pdf.rect(0, 0, pageW, 3.5, 'F');

  let y = margin + 6;

  // ── TITLE ──
  if (content.title) {
    pdf.setFont(fonts.heading, 'bold');
    pdf.setFontSize(orientation === 'landscape' ? 32 : 28);
    pdf.setTextColor(...C.dark);
    const titleLines = pdf.splitTextToSize(content.title, contentW);
    pdf.text(titleLines, margin, y);
    y += titleLines.length * (orientation === 'landscape' ? 13 : 11) + 1;
  }

  // ── SUBTITLE ──
  if (content.subtitle) {
    pdf.setFont(fonts.body, 'normal');
    pdf.setFontSize(13);
    pdf.setTextColor(...C.textLight);
    const subLines = pdf.splitTextToSize(content.subtitle, contentW);
    pdf.text(subLines, margin, y);
    y += subLines.length * 6 + 6;
  }

  // ── HIGHLIGHT BOX ──
  if (content.highlight) {
    pdf.setFont(fonts.body, 'bold');
    pdf.setFontSize(14);
    const hlText = pdf.splitTextToSize(content.highlight, contentW - 20);
    const boxH = hlText.length * 7 + 12;
    pdf.setFillColor(...C.accentLight);
    pdf.roundedRect(margin, y, contentW, boxH, 2.5, 2.5, 'F');
    pdf.setFillColor(...C.accent);
    pdf.rect(margin, y, 3.5, boxH, 'F');
    pdf.setTextColor(...C.dark);
    pdf.text(hlText, margin + 12, y + 8);
    y += boxH + 8;
  }

  // ── SECTIONS — 2-column grid, fill remaining space ──
  const sections = content.sections || [];
  if (sections.length > 0) {
    const gap = 10;
    const colW = (contentW - gap) / 2;

    // Calculate how much vertical space we have for sections
    const ctaSpace = content.call_to_action ? 14 : 0;
    const availableH = usableH - y - ctaSpace;

    // Distribute into columns
    const leftSections: any[] = [];
    const rightSections: any[] = [];
    sections.forEach((s: any, i: number) => {
      if (i % 2 === 0) leftSections.push(s);
      else rightSections.push(s);
    });

    // Measure total natural height of each column to compute card gaps
    const measureColumn = (colSections: any[], hSize: number, pSize: number, hLH: number, pLH: number): number => {
      let total = 0;
      for (const section of colSections) {
        pdf.setFont(fonts.body, 'bold');
        pdf.setFontSize(hSize);
        const hLines = pdf.splitTextToSize(section.heading || '', colW - 14);
        let cardH = hLines.length * hLH + 6;
        pdf.setFont(fonts.body, 'normal');
        pdf.setFontSize(pSize);
        for (const p of (section.points || [])) {
          const pLines = pdf.splitTextToSize(p, colW - 20);
          cardH += pLines.length * pLH + 2.5;
        }
        cardH += 5;
        total += cardH;
      }
      return total;
    };

    // First pass — measure at full size
    const leftNatH = measureColumn(leftSections, 13, 11, 6, 5.5);
    const rightNatH = measureColumn(rightSections, 13, 11, 6, 5.5);
    const maxNatH = Math.max(leftNatH, rightNatH);

    // Distribute extra space as gaps between cards
    const maxCards = Math.max(leftSections.length, rightSections.length);
    const extraSpace = Math.max(0, availableH - maxNatH);
    const cardGap = maxCards > 1 ? Math.min(extraSpace / maxCards, 12) : 6;

    // Check if content fits — if not, reduce font sizes
    const sectionFontSize = maxNatH > availableH * 0.95 ? 9.5 : 11;
    const headingFontSize = maxNatH > availableH * 0.95 ? 11 : 13;
    const lineH = sectionFontSize <= 10 ? 4.5 : 5.5;
    const headLineH = headingFontSize <= 11 ? 5 : 6;

    const drawColumn = (colSections: any[], startX: number, startY: number): number => {
      let cy = startY;
      for (const section of colSections) {
        const points = section.points || [];

        // Measure card
        pdf.setFont(fonts.body, 'bold');
        pdf.setFontSize(headingFontSize);
        const headingLines = pdf.splitTextToSize(section.heading || '', colW - 14);
        let cardH = headingLines.length * headLineH + 6;
        const pointLinesList: string[][] = [];
        pdf.setFont(fonts.body, 'normal');
        pdf.setFontSize(sectionFontSize);
        for (const p of points) {
          const pLines = pdf.splitTextToSize(p, colW - 20);
          pointLinesList.push(pLines);
          cardH += pLines.length * lineH + 2.5;
        }
        cardH += 5;

        // Card background
        pdf.setFillColor(...C.cardBg);
        pdf.roundedRect(startX, cy, colW, cardH, 2, 2, 'F');

        // Left accent bar
        pdf.setFillColor(...C.accent);
        pdf.roundedRect(startX, cy, 3, cardH, 1.5, 1.5, 'F');

        // Heading
        let innerY = cy + 7;
        pdf.setFont(fonts.body, 'bold');
        pdf.setFontSize(headingFontSize);
        pdf.setTextColor(...C.dark);
        pdf.text(headingLines, startX + 10, innerY);
        innerY += headingLines.length * headLineH + 3;

        // Points
        pdf.setFont(fonts.body, 'normal');
        pdf.setFontSize(sectionFontSize);
        pdf.setTextColor(...C.text);
        for (const pLines of pointLinesList) {
          pdf.setFillColor(...C.accent);
          pdf.circle(startX + 12.5, innerY - 1.2, 1, 'F');
          pdf.text(pLines, startX + 17, innerY);
          innerY += pLines.length * lineH + 2.5;
        }

        cy += cardH + cardGap;
      }
      return cy;
    };

    const colStartY = y;
    const leftEndY = drawColumn(leftSections, margin, colStartY);
    const rightEndY = drawColumn(rightSections, margin + colW + gap, colStartY);
    y = Math.max(leftEndY, rightEndY);
  }

  // ── CALL TO ACTION ──
  if (content.call_to_action) {
    // Position it with some breathing room, but not past the footer zone
    const ctaY = Math.min(y + 4, usableH - 8);
    pdf.setFont(fonts.body, 'bold');
    pdf.setFontSize(12);
    pdf.setTextColor(...C.accent);
    const ctaLines = pdf.splitTextToSize(content.call_to_action, contentW);
    pdf.text(ctaLines, margin, ctaY);
  }

  // ── FOOTER — subtle, bottom-right only ──
  pdf.setFont(fonts.body, 'normal');
  pdf.setFontSize(6.5);
  pdf.setTextColor(...C.textMuted);
  pdf.text('Generated by Mosaic', pageW - margin, pageH - 6, { align: 'right' });

  const title = (content.title || 'poster').replace(/[^a-zA-Z0-9_-]/g, '_').substring(0, 40);
  pdf.save(`${title}.pdf`);
}
